  @Bean
  public CommandLineRunner seedHexagrams(HexagramRepository repository) {
    return args -> {
      if (repository.count() > 0) {
        log.info("hexagram 表已有 {} 条数据，跳过种子灌入", repository.count());
        return;
      }
      List<Hexagram> all = new ArrayList<>();
      for (int i = 0; i < DATA.length; i++) {
        String[] row = DATA[i];
        Hexagram h = new Hexagram();
        h.setId(i + 1);
        h.setName(row[0]);
        h.setSymbol(String.valueOf((char) (SYMBOL_BASE + i)));
        h.setGuaCi(row[1]);
        h.setInterpretation(row[2]);
        h.setAdvice(row[3]);
        h.setLuckLevel(Integer.parseInt(row[4]));
        all.add(h);
      }
      repository.saveAll(all);
      log.info("hexagram 种子数据灌入完成：{} 卦", all.size());
    };
  }
