  /**
   * 构建一个花色的 14 张牌（Ace-10 + 侍从/骑士/王后/国王）
   */
  private void buildSuit(List<TarotCard> deck, String group, String suitCn, String suitEn, String[][] meanings) {
    String[] numberCn = {"一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "侍从", "骑士", "王后", "国王"};
    String[] numberEn = {"Ace", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Page", "Knight", "Queen", "King"};
    for (int i = 0; i < 14; i++) {
      String[] m = meanings[i];
      deck.add(card(suitCn + numberCn[i], numberEn[i] + " of " + suitEn, group, i + 1, m[0], m[1], m[2], m[3]));
    }
  }

  private TarotCard card(String name, String nameEn, String group, int number,
                         String upKw, String upMeaning, String revKw, String revMeaning) {
    return new TarotCard(name, nameEn, group, number, upKw, upMeaning, revKw, revMeaning);
  }

