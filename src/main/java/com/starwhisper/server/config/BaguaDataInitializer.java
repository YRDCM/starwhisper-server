  @Bean
  public CommandLineRunner initBaguaHexagrams(BaguaHexagramRepository repository) {
    return args -> {
      if (repository.count() > 0) {
        log.info("六十四卦数据已存在，跳过初始化（当前 {} 卦）", repository.count());
        return;
      }
      List<BaguaHexagram> all = buildAll();
      selfCheck(all); // 灌库前先自检，数据不对直接启动失败，好过带病运行
      repository.saveAll(all);
      log.info("六十四卦初始化完成");
    };
  }

  /**
   * 组卦：卦名/卦辞/解读/吉凶取自数据表；
   * 上下卦由卦序矩阵反查，六爻由爻位规则拼接，卦符按 Unicode 顺序生成
   */
  private List<BaguaHexagram> buildAll() {
    List<BaguaHexagram> all = new ArrayList<>();
    for (String[] row : HEXAGRAMS) {
      int seq = Integer.parseInt(row[0]);
      String[] trigrams = trigramsOf(seq); // [上卦, 下卦]
      // 六爻自下而上 = 下卦 3 爻 + 上卦 3 爻
      String lines = TRIGRAM_LINES.get(trigrams[1]) + TRIGRAM_LINES.get(trigrams[0]);
      // Unicode 卦符 U+4DC0 起按文王卦序排列，与卦序一一对应
      String symbol = new String(Character.toChars(0x4DC0 + seq - 1));
      all.add(new BaguaHexagram(seq, row[1], symbol, trigrams[0], trigrams[1],
          lines, row[2], row[3], row[4]));
    }
    return all;
  }

  /**
   * 由卦序在矩阵中反查 [上卦, 下卦]
   */
  private String[] trigramsOf(int seq) {
    for (int upper = 0; upper < 8; upper++) {
      for (int lower = 0; lower < 8; lower++) {
        if (SEQ_MATRIX[upper][lower] == seq) {
          return new String[]{TRIGRAM_ORDER[upper], TRIGRAM_ORDER[lower]};
        }
      }
    }
    throw new IllegalStateException("卦序矩阵里找不到卦序 " + seq);
  }

  /**
   * 自检：64 卦、卦序 1-64 不重不漏、lines 与上下卦一致、五组经典卦爻位抽查
   */
  private void selfCheck(List<BaguaHexagram> all) {
    if (all.size() != 64) {
      throw new IllegalStateException("六十四卦数据行数不对：" + all.size());
    }
    Set<Integer> seqs = new HashSet<>();
    for (BaguaHexagram h : all) {
      if (!seqs.add(h.getSeqNumber())) {
        throw new IllegalStateException("卦序重复：" + h.getSeqNumber());
      }
      // lines 必须等于 下卦爻位 + 上卦爻位
      String expect = TRIGRAM_LINES.get(h.getLowerTrigram()) + TRIGRAM_LINES.get(h.getUpperTrigram());
      if (!expect.equals(h.getLines())) {
        throw new IllegalStateException(h.getName() + " 的 lines 与上下卦不符：" + h.getLines() + " != " + expect);
      }
    }
    for (int seq = 1; seq <= 64; seq++) {
      if (!seqs.contains(seq)) {
        throw new IllegalStateException("卦序缺失：" + seq);
      }
    }
    // 经典卦爻位抽查（自下而上）：乾全阳、泰下三阳上三阴、否反之、既济阴阳相间、未济相反
    assertLines(all, 1, "111111");
    assertLines(all, 11, "111000");
    assertLines(all, 12, "000111");
    assertLines(all, 63, "101010");
    assertLines(all, 64, "010101");
  }

  private void assertLines(List<BaguaHexagram> all, int seq, String expected) {
    String actual = all.stream().filter(h -> h.getSeqNumber() == seq).findFirst().orElseThrow().getLines();
    if (!expected.equals(actual)) {
      throw new IllegalStateException("卦序 " + seq + " 爻位自检失败：" + actual + " != " + expected);
    }
  }
