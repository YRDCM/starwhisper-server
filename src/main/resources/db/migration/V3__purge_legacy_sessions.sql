-- ============================================================
-- V3：清理「改哈希之前」的遗留会话
--
-- 从 V3 之前的版本开始，user_session.token 存的是明文（32 位 UUID 去横线）。
-- 现在改成存明文令牌的 SHA-256 摘要（固定 64 位十六进制），查库时先哈希再比对，
-- 因此旧的 32 位行**永远不可能被匹配到**，属于纯垃圾数据。
--
-- 这些行留着有两个坏处：
--   1. 占地方，而且看起来"用户还有会话"，排查时会误导人
--   2. 任何人拿到数据库，里面这些明文 token 虽然已不能用，但仍是敏感数据
--
-- 影响：所有老用户需要重新登录一次（本来就必然发生，因为令牌校验方式变了）。
-- ============================================================
DELETE FROM user_session WHERE CHAR_LENGTH(token) <> 64;
